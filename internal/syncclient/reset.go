// UsageResetPlan is the server's read-only plan for a device usage reset:
// what ordinary device data a reset would clear right now. Every field is
// untrusted server data; the identity fields are validated against the
// locally bound device before the value is returned.
type UsageResetPlan struct {
	DeviceID          string  `json:"deviceId"`
	ApplicationID     string  `json:"applicationId"`
	ExternalSubjectID string  `json:"externalSubjectId"`
	DataEpoch         int64   `json:"dataEpoch"`
	ConsentRevision   int64   `json:"consentRevision"`
	RecordCount       int64   `json:"recordCount"`
	FirstDay          *string `json:"firstDay,omitempty"` // nullable YYYY-MM-DD
	LastDay           *string `json:"lastDay,omitempty"`  // nullable YYYY-MM-DD
}

// UsageResetRequest is the body of POST /v1/devices/usage-reset. The
// request id is generated by the recollect driver and reused verbatim
// for the completion call; the same id with the same payload is
// idempotent server-side, so a lost response can be retried by the
// driver with identical values.
type UsageResetRequest struct {
	RequestID               string `json:"requestId"`
	ExpectedDataEpoch       int64  `json:"expectedDataEpoch"`
	ExpectedConsentRevision int64  `json:"expectedConsentRevision"`
}

// UsageReset is the receipt of an accepted (or replayed) device usage
// reset: the epoch fence the server just installed. DataEpoch is the NEW
// epoch every subsequently exported batch must carry.
type UsageReset struct {
	RequestID         string    `json:"requestId"`
	DeviceID          string    `json:"deviceId"`
	ApplicationID     string    `json:"applicationId"`
	ExternalSubjectID string    `json:"externalSubjectId"`
	PreviousDataEpoch int64     `json:"previousDataEpoch"`
	DataEpoch         int64     `json:"dataEpoch"`
	ConsentRevision   int64     `json:"consentRevision"`
	SubjectGeneration int64     `json:"subjectGeneration"`
	ChangeSequence    int64     `json:"changeSequence"`
	ResetAt           time.Time `json:"resetAt"`
	Replay            bool      `json:"replay"`
	DeletedRecords    int64     `json:"deletedRecords"`
}

// UsageResetCompletionRequest is the body of POST
// /v1/devices/usage-reset/{requestId}/complete.
type UsageResetCompletionRequest struct {
	RequestID string `json:"requestId"`
	DataEpoch int64  `json:"dataEpoch"`
}

// UsageResetCompletion is the receipt of an accepted (or replayed)
// completion: the server has marked the rebuild finished for this epoch.
type UsageResetCompletion struct {
	RequestID      string    `json:"requestId"`
	DeviceID       string    `json:"deviceId"`
	DataEpoch      int64     `json:"dataEpoch"`
	ChangeSequence int64     `json:"changeSequence"`
	CompletedAt    time.Time `json:"completedAt"`
	Replay         bool      `json:"replay"`
}

// maxResetRequestIDLen bounds the driver-generated reset request id. The
// id travels in a URL path segment on the completion call, so it stays
// short and conservative.
const maxResetRequestIDLen = 128

// validateResetRequestID checks the driver-generated request id: it must
// be a non-empty, reasonably short token of URL-path-safe characters
// (letters, digits, dash, underscore, dot). The id is LOCAL input (the
// recollect driver generates it), not server data, so echoing it in
// errors is safe.
func validateResetRequestID(requestID string) error {
	requestID = strings.TrimSpace(requestID)
	if requestID == "" {
		return errors.New("usage reset request id is required")
	}
	if len(requestID) > maxResetRequestIDLen {
		return fmt.Errorf("usage reset request id is too long (max %d characters)", maxResetRequestIDLen)
	}
	for _, r := range requestID {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case r == '-' || r == '_' || r == '.':
		default:
			return errors.New("usage reset request id may contain only letters, digits, '-', '_' and '.'")
		}
	}
	return nil
}

// resetResponseCommon folds the shared error handling of the three reset
// endpoints. Known terminal codes keep their sentinels; 401/403 stay the
// device-unauthorized fence; 409 maps to ErrResetConflict (expected epoch
// or consent revision moved, or the same request id arrived with a
// different payload); every other failure is a fixed status-only message.
// The server's free-text code and message are never echoed.
func resetResponseError(status int, code string) error {
	switch code {
	case "device_revoked":
		return fmt.Errorf("%w: the server revoked this device (HTTP %d); the reset flow stops and the collector never re-binds automatically", ErrDeviceRevoked, status)
	case "subject_deleted":
		return fmt.Errorf("%w: the server deleted the subject (HTTP %d); the reset flow stops and the collector never re-binds automatically", ErrSubjectDeleted, status)
	}
	switch status {
	case http.StatusUnauthorized, http.StatusForbidden:
		return fmt.Errorf("%w: the usage reset endpoint rejected the device credentials (HTTP %d)", ErrDeviceUnauthorized, status)
	case http.StatusConflict:
		return fmt.Errorf("%w: the server refused the usage reset request (HTTP %d); the expected data epoch or consent revision no longer matches, or the request id was reused with a different payload; re-read the plan before retrying", ErrResetConflict, status)
	}
	if code != "" {
		return fmt.Errorf("usage reset request failed: status %d (server error code: other)", status)
	}
	return fmt.Errorf("usage reset request failed: status %d", status)
}

// identityMatches compares a server-reported identity field against the
// locally bound one. An empty local value (a hand-written state file)
// cannot disprove anything, so only a non-empty mismatch fails.
func identityMatches(received, local string) bool {
	return local == "" || received == local
}

// checkResetIdentity validates a reset response's identity block against
// the locally bound device. A hostile or buggy server answering with
// another device's or subject's reset must never feed the recollect
// driver's journal transition. The server's values are never echoed in
// the error.
func checkResetIdentity(deviceID, applicationID, externalSubjectID string, st statedir.DeviceState) error {
	if deviceID != st.DeviceID {
		return fmt.Errorf("%w: the usage reset response describes a different device; refusing to apply it", ErrDeviceUnauthorized)
	}
	if !identityMatches(applicationID, st.ApplicationID) || !identityMatches(externalSubjectID, st.ExternalSubjectID) {
		return fmt.Errorf("%w: the usage reset response identity does not match the bound subject; refusing to apply it", ErrDeviceUnauthorized)
	}
	return nil
}

// resetReflectsSecret reports whether any string field of a reset
// response that the caller keeps contains the device secret
// (case-insensitive; the secret is hex). Mirrors the self-snapshot
// reflection guard: the endpoints just saw the credential in the
// Authorization header, and every returned string travels on into the
// recollect journal and human output.
func resetReflectsSecret(secret string, values ...string) bool {
	if secret == "" {
		return false
	}
	needle := strings.ToLower(secret)
	for _, value := range values {
		if value != "" && strings.Contains(strings.ToLower(value), needle) {
			return true
		}
	}
	return false
}

// loadResetState performs the shared prologue of the three reset client
// calls: load the bound device state, resolve the server URL, and build
// the redirect-refusing client.
func loadResetState(store statedir.Store, opt Options) (statedir.DeviceState, string, *http.Client, error) {
	st, err := store.Load()
	if err != nil {
		return statedir.DeviceState{}, "", nil, err
	}
	if st.DeviceID == "" || st.DeviceSecret == "" {
		return statedir.DeviceState{}, "", nil, errors.New("device is not bound; run toktrail bind first")
	}
	serverURL := strings.TrimSpace(opt.ServerURL)
	if serverURL == "" {
		serverURL = st.ServerURL
	}
	if serverURL == "" {
		serverURL = "http://127.0.0.1:3211"
	}
	client := noRedirectClient(opt.HTTPClient)
	return st, serverURL, client, nil
}

// FetchUsageResetPlan fetches GET /v1/devices/usage-reset-plan with the
// device's own credentials: the read-only plan of what a usage reset
// would clear (record count, day range, current epoch and consent
// revision). It performs no writes anywhere, sends nothing but the
// authenticated GET, and is safe to call in a force-recollect dry run.
//
// The call deliberately does NOT enforce the force-recollect journal
// guard or the data-epoch fences: it is a reset-flow read. Ordinary
// flows have no reason to call it.
//
// Failure handling matches the device self check: revoked or deleted
// devices fail with ErrDeviceRevoked / ErrSubjectDeleted, rejected
// credentials with ErrDeviceUnauthorized, a structurally invalid answer
// with ErrSelfProtocol, and every transport/HTTP failure with a fixed
// status-only message. One attempt, no retry policy.
func FetchUsageResetPlan(ctx context.Context, store statedir.Store, opt Options) (UsageResetPlan, error) {
	st, serverURL, client, err := loadResetState(store, opt)
	if err != nil {
		return UsageResetPlan{}, err
	}
	endpoint, err := joinURL(serverURL, "/v1/devices/usage-reset-plan")
	if err != nil {
		return UsageResetPlan{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
	if err != nil {
		return UsageResetPlan{}, err
	}
	req.Header.Set("Authorization", "Bearer "+st.DeviceID+"."+st.DeviceSecret)
	resp, err := client.Do(req)
	if err != nil {
		return UsageResetPlan{}, wrapTransportError("usage reset plan fetch", err)
	}
	defer resp.Body.Close()
	var body struct {
		Plan  *UsageResetPlan `json:"plan,omitempty"`
		Error *struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error,omitempty"`
	}
	if err := json.NewDecoder(capResponseBody(resp.Body)).Decode(&body); err != nil {
		if errors.Is(err, errResponseBodyTooLarge) {
			return UsageResetPlan{}, fmt.Errorf("%w: usage reset plan response exceeded the %d MiB body limit (status %d)", ErrSelfProtocol, maxResponseBodyBytes>>20, resp.StatusCode)
		}
		return UsageResetPlan{}, fmt.Errorf("%w: usage reset plan response was not decodable (status %d): %w", ErrSelfProtocol, resp.StatusCode, safeDecodeErrorOf(err))
	}
	if resp.StatusCode != http.StatusOK {
		code := ""
		if body.Error != nil {
			code = body.Error.Code
		}
		return UsageResetPlan{}, resetResponseError(resp.StatusCode, code)
	}
	if body.Plan == nil {
		return UsageResetPlan{}, fmt.Errorf("%w: usage reset plan response missing the plan object", ErrSelfProtocol)
	}
	if resetReflectsSecret(st.DeviceSecret, body.Plan.DeviceID, body.Plan.ApplicationID, body.Plan.ExternalSubjectID) {
		return UsageResetPlan{}, fmt.Errorf("%w: usage reset plan response carried reflected credential material; failing closed without applying any part of the plan", ErrSelfProtocol)
	}
	if err := checkResetIdentity(body.Plan.DeviceID, body.Plan.ApplicationID, body.Plan.ExternalSubjectID, st); err != nil {
		return UsageResetPlan{}, err
	}
	if body.Plan.DataEpoch < 0 || body.Plan.RecordCount < 0 || body.Plan.ConsentRevision <= 0 {
		return UsageResetPlan{}, fmt.Errorf("%w: usage reset plan reported an invalid epoch, revision or record count", ErrSelfProtocol)
	}
	return *body.Plan, nil
}

// RequestUsageReset performs POST /v1/devices/usage-reset: the
// server-side half of a force-recollect. The server validates the
// device's live authorization and the expected epoch/consent revision,
// clears the device's ordinary data atomically, advances its data epoch,
// and returns the new fence. A repeated call with the same request id
// and the same payload replays the original receipt; the same id with a
// different payload is a conflict (ErrResetConflict).
//
// The collector NEVER calls this on its own — only the recollect driver
// does, after its journal exists. This method performs no local writes:
// installing the new epoch into the device state is the driver's journal
// transition, not this client's job.
//
// One attempt, no retry policy: a transport failure after the server
// applied the reset is resolved by retrying the identical request (the
// receipt is idempotent server-side), which the driver decides.
func RequestUsageReset(ctx context.Context, store statedir.Store, opt Options, req UsageResetRequest) (UsageReset, error) {
	if err := validateResetRequestID(req.RequestID); err != nil {
		return UsageReset{}, err
	}
	if req.ExpectedDataEpoch < 0 {
		return UsageReset{}, errors.New("expected data epoch must be non-negative")
	}
	if req.ExpectedConsentRevision <= 0 {
		return UsageReset{}, errors.New("expected consent revision must be positive")
	}
	st, serverURL, client, err := loadResetState(store, opt)
	if err != nil {
		return UsageReset{}, err
	}
	payload, err := json.Marshal(req)
	if err != nil {
		return UsageReset{}, err
	}
	endpoint, err := joinURL(serverURL, "/v1/devices/usage-reset")
	if err != nil {
		return UsageReset{}, err
	}
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(payload))
	if err != nil {
		return UsageReset{}, err
	}
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.Header.Set("Authorization", "Bearer "+st.DeviceID+"."+st.DeviceSecret)
	resp, err := client.Do(httpReq)
	if err != nil {
		return UsageReset{}, wrapTransportError("usage reset request", err)
	}
	defer resp.Body.Close()
	var body struct {
		Reset *UsageReset `json:"reset,omitempty"`
		Error *struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error,omitempty"`
	}
	if err := json.NewDecoder(capResponseBody(resp.Body)).Decode(&body); err != nil {
		if errors.Is(err, errResponseBodyTooLarge) {
			return UsageReset{}, fmt.Errorf("usage reset response exceeded the %d MiB body limit (status %d); the reset may have been applied — retry the identical request id to obtain the receipt", maxResponseBodyBytes>>20, resp.StatusCode)
		}
		return UsageReset{}, fmt.Errorf("usage reset response was not decodable (status %d): %w; the reset may have been applied — retry the identical request id to obtain the receipt", resp.StatusCode, safeDecodeErrorOf(err))
	}
	if resp.StatusCode != http.StatusOK && resp.StatusCode != http.StatusAccepted && resp.StatusCode != http.StatusCreated {
		code := ""
		if body.Error != nil {
			code = body.Error.Code
		}
		return UsageReset{}, resetResponseError(resp.StatusCode, code)
	}
	if body.Reset == nil {
		return UsageReset{}, fmt.Errorf("%w: usage reset response missing the reset receipt", ErrSelfProtocol)
	}
	if body.Reset.RequestID != req.RequestID {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt names a different request id than the one submitted; refusing to apply it", ErrSelfProtocol)
	}
	if resetReflectsSecret(st.DeviceSecret, body.Reset.RequestID, body.Reset.DeviceID, body.Reset.ApplicationID, body.Reset.ExternalSubjectID) {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt carried reflected credential material; failing closed without applying any part of it", ErrSelfProtocol)
	}
	if err := checkResetIdentity(body.Reset.DeviceID, body.Reset.ApplicationID, body.Reset.ExternalSubjectID, st); err != nil {
		return UsageReset{}, err
	}
	// Critical-field consistency: a receipt missing or contradicting the
	// reset contract must never feed the recollect driver's journal
	// transition. The reset advances the epoch by exactly one, never
	// touches the consent revision (the CAS value that just matched is
	// still current), and stamps a real time with a live subject
	// generation and a positive fence sequence; the recollect driver
	// re-validates independently, but this client refuses to hand on a
	// structurally impossible receipt.
	if body.Reset.DataEpoch <= 0 || body.Reset.DataEpoch != body.Reset.PreviousDataEpoch+1 {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt reports an impossible epoch transition (previous %d, next %d); refusing to apply it", ErrSelfProtocol, body.Reset.PreviousDataEpoch, body.Reset.DataEpoch)
	}
	if body.Reset.ConsentRevision != req.ExpectedConsentRevision {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt reports consent revision %d but the request was accepted against %d; refusing to apply it", ErrSelfProtocol, body.Reset.ConsentRevision, req.ExpectedConsentRevision)
	}
	if body.Reset.SubjectGeneration <= 0 {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt carries no subject generation; refusing to apply it", ErrSelfProtocol)
	}
	if body.Reset.ChangeSequence <= 0 {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt carries a non-positive change sequence; refusing to apply it", ErrSelfProtocol)
	}
	if body.Reset.DeletedRecords < 0 {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt reported a negative deleted-record count", ErrSelfProtocol)
	}
	if body.Reset.ResetAt.IsZero() {
		return UsageReset{}, fmt.Errorf("%w: usage reset receipt carries no reset timestamp; refusing to apply it", ErrSelfProtocol)
	}
	return *body.Reset, nil
}

// CompleteUsageReset performs POST /v1/devices/usage-reset/{requestId}/complete:
// the marker that the device finished rebuilding its data under the new
// epoch. The SERVER's acceptance is what this receipt proves — the
// server-side projection of the completion is asynchronous, and the
// recollect driver separately checks the projection marker before it
// trusts the rebuild as visible. The server accepts only the latest
// task under the current epoch; a repeated call with the same request id
// replays the original completion.
//
// Like RequestUsageReset this is recollect-driver-only and performs no
// local writes. One attempt, no retry policy.
func CompleteUsageReset(ctx context.Context, store statedir.Store, opt Options, req UsageResetCompletionRequest) (UsageResetCompletion, error) {
	if err := validateResetRequestID(req.RequestID); err != nil {
		return UsageResetCompletion{}, err
	}
	if req.DataEpoch < 0 {
		return UsageResetCompletion{}, errors.New("completion data epoch must be non-negative")
	}
	st, serverURL, client, err := loadResetState(store, opt)
	if err != nil {
		return UsageResetCompletion{}, err
	}
	payload, err := json.Marshal(struct {
		DataEpoch int64 `json:"dataEpoch"`
	}{req.DataEpoch})
	if err != nil {
		return UsageResetCompletion{}, err
	}
	endpoint, err := joinURL(serverURL, "/v1/devices/usage-reset/"+req.RequestID+"/complete")
	if err != nil {
		return UsageResetCompletion{}, err
	}
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(payload))
	if err != nil {
		return UsageResetCompletion{}, err
	}
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.Header.Set("Authorization", "Bearer "+st.DeviceID+"."+st.DeviceSecret)
	resp, err := client.Do(httpReq)
	if err != nil {
		return UsageResetCompletion{}, wrapTransportError("usage reset completion", err)
	}
	defer resp.Body.Close()
	var body struct {
		Completion *UsageResetCompletion `json:"completion,omitempty"`
		Error      *struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error,omitempty"`
	}
	if err := json.NewDecoder(capResponseBody(resp.Body)).Decode(&body); err != nil {
		if errors.Is(err, errResponseBodyTooLarge) {
			return UsageResetCompletion{}, fmt.Errorf("usage reset completion response exceeded the %d MiB body limit (status %d); the completion may have been recorded — retry the identical request id", maxResponseBodyBytes>>20, resp.StatusCode)
		}
		return UsageResetCompletion{}, fmt.Errorf("usage reset completion response was not decodable (status %d): %w; the completion may have been recorded — retry the identical request id", resp.StatusCode, safeDecodeErrorOf(err))
	}
	if resp.StatusCode != http.StatusOK && resp.StatusCode != http.StatusAccepted && resp.StatusCode != http.StatusCreated {
		code := ""
		if body.Error != nil {
			code = body.Error.Code
		}
		return UsageResetCompletion{}, resetResponseError(resp.StatusCode, code)
	}
	if body.Completion == nil {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion response missing the completion object", ErrSelfProtocol)
	}
	if body.Completion.RequestID != req.RequestID {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion names a different request id than the one submitted; refusing to apply it", ErrSelfProtocol)
	}
	if body.Completion.DeviceID != st.DeviceID {
		return UsageResetCompletion{}, fmt.Errorf("%w: the usage reset completion describes a different device; refusing to apply it", ErrDeviceUnauthorized)
	}
	if resetReflectsSecret(st.DeviceSecret, body.Completion.RequestID, body.Completion.DeviceID) {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion carried reflected credential material; failing closed without applying any part of it", ErrSelfProtocol)
	}
	if body.Completion.DataEpoch != req.DataEpoch {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion reports data epoch %d but epoch %d was submitted; refusing to apply it", ErrSelfProtocol, body.Completion.DataEpoch, req.DataEpoch)
	}
	// Critical-field consistency: the completion belongs to a real reset
	// task, so the epoch is positive, the fence sequence is a positive
	// integer, and the server stamped a real completion time. A receipt
	// missing any of these never reaches the driver.
	if body.Completion.DataEpoch <= 0 {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion reports a non-positive data epoch; refusing to apply it", ErrSelfProtocol)
	}
	if body.Completion.ChangeSequence <= 0 {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion reports a non-positive change sequence; refusing to apply it", ErrSelfProtocol)
	}
	if body.Completion.CompletedAt.IsZero() {
		return UsageResetCompletion{}, fmt.Errorf("%w: usage reset completion carries no completion timestamp; refusing to apply it", ErrSelfProtocol)
	}
	return *body.Completion, nil
}
